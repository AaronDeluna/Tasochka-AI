def main():
    print(f"Loading model from {MODEL_PATH}")
    print(f"With LoRA adapter from {ADAPTER_PATH}")
    # lazy=True — грузит веса по требованию, экономит ~5 ГБ пиковой памяти
    model, tokenizer = load(MODEL_PATH, adapter_path=ADAPTER_PATH, lazy=True)
    print("Model loaded (lazy).\n")

    sampler = make_sampler(temp=TEMP, top_p=TOP_P)

    OUT_DIR.mkdir(exist_ok=True)
    ts = datetime.datetime.now().strftime("%Y-%m-%d_%H-%M")
    out_path = OUT_DIR / f"eval_{ts}.md"

    total = sum(len(qs) for qs in QUESTIONS.values())

    with open(out_path, "w", encoding="utf-8") as f:
        f.write(f"# Прогон Tasochka AI — {ts}\n\n")
        f.write(f"- Модель: `{MODEL_PATH}`\n")
        f.write(f"- LoRA: `{ADAPTER_PATH}`\n")
        f.write(f"- Параметры: max_tokens={MAX_TOKENS}, temp={TEMP}, top_p={TOP_P}\n")
        f.write(f"- Всего вопросов: {total}\n\n---\n\n")

        i = 0
        for topic, qs in QUESTIONS.items():
            f.write(f"## {topic}\n\n")
            print(f"\n=== {topic} ===")
            for q in qs:
                i += 1
                # Применяем chat template Gemma
                messages = [{"role": "user", "content": q}]
                prompt = tokenizer.apply_chat_template(
                    messages, add_generation_prompt=True, tokenize=False
                )
                answer = generate(
                    model, tokenizer,
                    prompt=prompt,
                    max_tokens=MAX_TOKENS,
                    sampler=sampler,
                    verbose=False,
                )
                # mlx-lm уже возвращает только ответ (без промпта), но почистим артефакты
                answer = answer.strip()

                print(f"[{i:>3}/{total}] Q: {q}")
                print(f"        A: {answer[:120]}{'...' if len(answer) > 120 else ''}")

                f.write(f"**Q{i}: {q}**\n\n")
                f.write(f"{answer}\n\n---\n\n")
                f.flush()

    print(f"\nГотово. Полный лог: {out_path}")
    print(f"Открыть: open -a TextEdit \"{out_path}\"")


if __name__ == "__main__":
    main()
