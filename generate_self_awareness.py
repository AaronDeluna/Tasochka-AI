def fmt_turn(role: str, content: str) -> str:
    return f"<{role}>\n{content.strip()}\n</{role}>\n"


def fmt_dialog(turns: list[tuple[str, str]]) -> str:
    return "".join(fmt_turn(r, c) for r, c in turns) + "\n"


